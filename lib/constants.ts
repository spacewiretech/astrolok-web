/* ------------------------------------------------------------------
   Frame sequences
   ------------------------------------------------------------------ */

export type FrameSequenceName = "palm" | "face" | "astrology" | "chat";

/**
 * Where frame sequences are served from.
 *  - "optimized": WebP files generated by `npm run optimize:frames` (recommended)
 *  - "original":  the untouched source PNGs in /public/frames
 * Set NEXT_PUBLIC_FRAME_SOURCE to switch. Optimized frames automatically fall
 * back to the original PNG if a WebP file is missing.
 */
export const FRAME_SOURCE: "optimized" | "original" =
  process.env.NEXT_PUBLIC_FRAME_SOURCE === "original" ? "original" : "optimized";

export const FRAME_COUNT = 120;

export function getFrameSources(name: FrameSequenceName) {
  const original = { framePath: `/frames/${name}/frame_`, frameExt: "png" };
  if (FRAME_SOURCE === "original") {
    return { ...original, smallFramePath: undefined, fallback: undefined };
  }
  return {
    framePath: `/frames-optimized/${name}/frame_`,
    smallFramePath: `/frames-optimized/${name}/sm/frame_`,
    frameExt: "webp",
    fallback: original,
  };
}

