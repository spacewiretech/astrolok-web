export type ReadingFeature = {
  id: string;
  sequence: FrameSequenceName;
  eyebrow: string;
  title: string;
  body: string;
  cta: string;
  /** Short alt text for the scroll animation (one canvas, not per frame) */
  canvasLabel: string;
  /** One plain sentence describing the reading for screen readers and crawlers; not shown visually */
  seoDescription: string;
  name: string;
  /** One-line hook shown under the name in the readings index */
  teaser: string;
  /** What the visual highlights as the scan progresses */
  stages: readonly string[];
  stagesLabel: string;
  /**
   * Scroll progress (0–1) at which each stage lights up. Defaults to even spacing.
   * Set it when the frames have a clear timeline, so the labels match what is on screen.
   */
  stageAt?: readonly number[];
  /** Small label above the heading, only where the heading doesn't name the feature */
  label?: string;
  /** Short supporting line under the stages */
  note?: string;
  /**
   * Desktop composition. The experiences share one system but not one layout:
   *  - "split":        visual on the right, explanation beside it (palm)
   *  - "portrait":     full-bleed visual, copy anchored bottom-left (face)
   *  - "cosmic":       full-bleed visual, copy above and below the chart (astrology)
   *  - "conversation": phone in the centre, copy left, the chat's steps right (chat)
   */
  layout: "split" | "portrait" | "cosmic" | "conversation";
};

